/**
 * The ingested creature library.
 *
 * Written as a compact table rather than one object per creature: this is reference data
 * with the same eight fields repeated, and a table is both shorter to read and harder to
 * get inconsistent. `toMonsters()` expands it into the domain shape.
 *
 * Realistic Monster Manual content, deliberately spanning the whole difficulty range and
 * every creature type, so the library's filters, its sort and its long-list behaviour can
 * all be exercised against something that looks like the real thing.
 */
